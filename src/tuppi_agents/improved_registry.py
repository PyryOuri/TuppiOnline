@dataclass(frozen=True, slots=True)
class PolicyLayer:
    """One behavioural change applied above a registered Phase 4 profile.

    ``supersedes`` names the catalogued Phase 4 rule the layer replaces, or is
    ``None`` when the layer only adds.  ``introduces`` names the score components
    the layer prepends, which is what the diagnostics channel reports.
    ``parameters`` carries every materially behavioural setting; anything that
    cannot change a selected action belongs in the policy's description instead.

    ``catalogued`` is always ``False`` and is recorded rather than assumed: every
    rule id in a candidate must resolve in ``rule_catalogue``, whose provenance
    constraints are tied to the frozen Phase 4 profiles, so these layers are
    expressed as components instead.  ``void_lead.VOID_LEAD_REASON_CODE`` carries
    the same explanation at the diagnostics level.
    """

    layer_id: str
    supersedes: str | None
    introduces: tuple[str, ...]
    parameters: tuple[tuple[str, object], ...]
    catalogued: bool = False

    def __post_init__(self) -> None:
        if not isinstance(self.layer_id, str) or not self.layer_id:
            raise AgentsValidationError("layer_id must be a nonempty string")
        if self.supersedes is not None and (
            not isinstance(self.supersedes, str) or not self.supersedes
        ):
            raise AgentsValidationError("supersedes must be null or a nonempty string")
        if type(self.introduces) is not tuple or not self.introduces:
            raise AgentsValidationError("a layer must introduce at least one component")
        if any(not isinstance(item, str) or not item for item in self.introduces):
            raise AgentsValidationError("introduced components must be nonempty strings")
        if type(self.parameters) is not tuple:
            raise AgentsValidationError("layer parameters must be a tuple of pairs")
        seen: set[str] = set()
        for pair in self.parameters:
            if type(pair) is not tuple or len(pair) != 2:
                raise AgentsValidationError("each layer parameter must be a pair")
            name, value = pair
            if not isinstance(name, str) or not name:
                raise AgentsValidationError("layer parameter names must be nonempty")
            if name in seen:
                raise AgentsValidationError(f"duplicate layer parameter {name!r}")
            seen.add(name)
            if type(value) not in (str, int, float, bool):
                raise AgentsValidationError(
                    f"layer parameter {name!r} must be a JSON scalar"
                )
        if self.catalogued is not False:
            raise AgentsValidationError("improved layers are never catalogued rules")

    def to_data(self) -> dict[str, object]:
        return {
            "catalogued": self.catalogued,
            "introduces": list(self.introduces),
            "layer_id": self.layer_id,
            "parameters": {name: value for name, value in sorted(self.parameters)},
            "supersedes": self.supersedes,
        }


@dataclass(frozen=True, slots=True)
class ImprovedPolicy:
    """The complete identity-bearing declaration of one improved policy."""

    profile_key: str
    base_profile_key: str
    base_improved_key: str | None
    agent_family: str
    implementation_reference: str
    policy_schema_version: str
    layers: tuple[PolicyLayer, ...]
    description: str

    def __post_init__(self) -> None:
        for label, value in (
            ("profile_key", self.profile_key),
            ("base_profile_key", self.base_profile_key),
            ("agent_family", self.agent_family),
            ("implementation_reference", self.implementation_reference),
            ("policy_schema_version", self.policy_schema_version),
            ("description", self.description),
        ):
            if not isinstance(value, str) or not value:
                raise AgentsValidationError(f"{label} must be a nonempty string")
        if type(self.layers) is not tuple or not self.layers:
            raise AgentsValidationError("an improved policy must declare a layer")
        if any(not isinstance(item, PolicyLayer) for item in self.layers):
            raise AgentsValidationError("layers must be PolicyLayer values")
        if len({item.layer_id for item in self.layers}) != len(self.layers):
            raise AgentsValidationError("layer ids must be unique within a policy")


