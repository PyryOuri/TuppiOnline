"""Content-addressed identities for the improved partner-aware policies.

``partner_aware_lead_v2`` and ``partner_aware_discard_v3`` are deliberately not
Phase 4 profiles.  Registering either one would change the frozen baseline that
every Phase 4, 5 and 6 result is quoted against, which is why
``void_lead.VOID_LEAD_PROFILE_KEY`` exists beside ``BASE_PROFILE_KEY`` instead of
inside ``registry.STRATEGIC_PROFILE_KEYS``.

But a corpus generated by one of these policies has to be able to *name* the
policy that played, and the interim convention - prefixing the base profile's
identity, ``"partner_aware_lead_v2:agent:sha256:d8b4..."`` - names the base
profile rather than the improved behaviour.  Changing a lead rule leaves that
string untouched, so it cannot serve as the identity of a generated artifact.

This module mints a real ``agent:sha256:...`` over the improved policy's *own*
behavioural content: the base profile's identity, plus the ordered tuple of
behavioural layers applied above it, plus each layer's materially behavioural
parameters.  Two consequences follow by construction:

* changing a layer parameter, adding a layer, or reordering the stack produces a
  different ``agent_id``, exactly as editing a ``HeuristicProfile`` threshold
  produces a different ``profile_id``;
* re-wording a description does not, because ``AgentSpecification.identity_data``
  excludes the description - the same rule ``profiles.HeuristicProfile`` follows.

It registers nothing with Phase 4.  ``phase4_agent_specifications`` and every
frozen ``agent_id`` are untouched, and ``improved_registry`` is not reachable
from any Phase 4 profile.

This is a *harness* module in the sense of ``tests/agents/test_architecture.py``:
it builds specifications and never participates in a decision.

The two identity conventions coexist on purpose for now.  The existing
constructors in ``void_lead`` and ``nolo_discard`` keep stamping the prefixed
string, because the private-alpha server, ``schemas/network/*``,
``ReferencePolicy.swift`` and the persisted room state all read it, and
``docs/valuation/nolo_ducking_results.md`` records that changing it carelessly
breaks restart recovery.  Use :func:`construct_improved_agent` for anything whose
output is an artifact that must be citable; the four-surface profile change
should collapse the two conventions onto this one.
"""

