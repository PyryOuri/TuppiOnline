def improved_policies() -> dict[str, ImprovedPolicy]:
    """The immutable declarations, keyed by improved profile key."""

    return {policy.profile_key: policy for policy in _IMPROVED_POLICIES}


def _base_specification(base_profile_key: str) -> AgentSpecification:
    from .registry import phase4_specifications_by_profile_key

    specifications = phase4_specifications_by_profile_key()
    if base_profile_key not in specifications:
        raise AgentsValidationError(
            f"unregistered base agent profile {base_profile_key!r}"
        )
    return specifications[base_profile_key]


def improved_configuration(
    policy: ImprovedPolicy, *, base: AgentSpecification, base_improved_agent_id: str | None
) -> dict[str, object]:
    """The canonical identity-bearing configuration of one improved policy.

    ``base_profile_id`` is carried rather than the whole profile object: it is
    already a content address over the profile's behavioural content, so
    including both would let one change move two fields.
    """

    from .factory import profile_of

    profile = profile_of(base)
    return {
        "action_ordering_id": ACTION_ORDERING_ID,
        "base_agent_id": base.agent_id,
        "base_improved_agent_id": base_improved_agent_id,
        "base_profile_id": profile.profile_id,
        "base_profile_key": policy.base_profile_key,
        "belief_model": None,
        "diagnostics_schema": DIAGNOSTICS_SCHEMA_VERSION,
        "endgame_solver": None,
        "hidden_hand_sampling": None,
        "improved_policy_schema": policy.policy_schema_version,
        "improved_registry_schema": IMPROVED_REGISTRY_SCHEMA_VERSION,
        "layers": [layer.to_data() for layer in policy.layers],
        "learning": None,
        "observation_only": True,
        "profile_key": policy.profile_key,
        "rollout_budget": None,
        "rule_catalogue_schema": RULE_CATALOGUE_SCHEMA_VERSION,
        "search": None,
        "tie_break_id": TIE_BREAK_ID,
    }


def specification_for_improved_policy(
    policy: ImprovedPolicy, *, base_improved_agent_id: str | None = None
) -> AgentSpecification:
    """Build the immutable, content-addressed specification of one policy."""

    if not isinstance(policy, ImprovedPolicy):
        raise AgentsValidationError("policy must be an ImprovedPolicy")
    base = _base_specification(policy.base_profile_key)
    return AgentSpecification.build(
        agent_family=policy.agent_family,
        configuration_version=IMPROVED_AGENT_VERSION,
        implementation_reference=policy.implementation_reference,
        ruleset_compatibility=(RULESET_ID,),
        observation_schema_compatibility=(OBSERVATION_SCHEMA_ID,),
        determinism=DeterminismClass.DETERMINISTIC,
        seed_policy=SeedPolicy.NONE,
        configuration=improved_configuration(
            policy, base=base, base_improved_agent_id=base_improved_agent_id
        ),
        model_checkpoint_id=None,
        search_budget=None,
        partner_convention_id=None,
        description=policy.description,
    )


def improved_specifications_by_profile_key() -> dict[str, AgentSpecification]:
    """Every improved policy's immutable specification, keyed by profile key.

    Chained policies carry the identity of the improved policy they extend, so
    ``partner_aware_discard_v3``'s address changes if ``partner_aware_lead_v2``'s
    behaviour changes underneath it.

    Memoised, and the reason is measured rather than defensive. Resolving these
    means content-addressing each specification, and ``factory`` consults this
    mapping once per *agent construction* to match an improved specification by
    identity. A PIMC decision constructs four agents per rollout, so at W=8 that
    was 416 calls and 2.74 s of a 5.66 s decision — more than the rollouts
    themselves. The declarations are a module-level constant and nothing mutates
    them, so there is nothing to invalidate; a fresh dict is returned each call
    so no caller can reach the cached mapping.
    """

    return dict(_resolved_improved_specifications())


def _resolved_improved_specifications() -> tuple[tuple[str, AgentSpecification], ...]:
    global _RESOLVED_CACHE
    if _RESOLVED_CACHE is None:
        _RESOLVED_CACHE = _resolve_improved_specifications()
    return _RESOLVED_CACHE


def _resolve_improved_specifications() -> tuple[tuple[str, AgentSpecification], ...]:
    declared = improved_policies()
    resolved: dict[str, AgentSpecification] = {}
    for key in IMPROVED_PROFILE_KEYS:
        policy = declared[key]
        parent_id: str | None = None
        if policy.base_improved_key is not None:
            if policy.base_improved_key not in resolved:
                raise AgentsValidationError(
                    f"{key!r} extends {policy.base_improved_key!r}, which is not "
                    "declared before it"
                )
            parent_id = resolved[policy.base_improved_key].agent_id
        resolved[key] = specification_for_improved_policy(
            policy, base_improved_agent_id=parent_id
        )
    if len({spec.agent_id for spec in resolved.values()}) != len(resolved):
        raise AgentsValidationError(
            "two improved policies produced the same agent identity"
        )
    phase4 = {
        spec.agent_id
        for spec in _phase4_specifications().values()
    }
    collisions = phase4 & {spec.agent_id for spec in resolved.values()}
    if collisions:
        raise AgentsValidationError(
            "an improved policy collided with a frozen Phase 4 identity"
        )
    return tuple(resolved.items())


def _phase4_specifications() -> Mapping[str, AgentSpecification]:
    from .registry import phase4_specifications_by_profile_key

    return phase4_specifications_by_profile_key()


def _policy_class(profile_key: str):
    if profile_key == "partner_aware_lead_v2":
        from .void_lead import VoidSeekingPartnerAwarePolicy

        return VoidSeekingPartnerAwarePolicy
    if profile_key == "partner_aware_discard_v3":
        from .nolo_discard import LiabilityDiscardPolicy

        return LiabilityDiscardPolicy
    if profile_key == "partner_aware_lead_v3":
        from .refined_play import RefinedPartnerAwarePolicy

        return RefinedPartnerAwarePolicy
    raise AgentsValidationError(f"unknown improved profile {profile_key!r}")


def construct_improved_agent(profile_key: str, *, seat: int):
    """One improved policy for *seat*, reporting its content-addressed identity.

    Unlike ``void_lead.construct_void_lead_agent`` the returned policy's
    ``agent_id`` is a real ``agent:sha256:...`` over the improved behaviour, so an
    artifact that records it can be cited and reproduced.  Prefer this
    constructor for anything that writes a record.
    """

    if type(seat) is not int or seat not in range(4):
        raise AgentsValidationError("seat must be an integer in 0..3")
    specifications = improved_specifications_by_profile_key()
    if profile_key not in specifications:
        raise AgentsValidationError(f"unknown improved profile {profile_key!r}")
    return improved_agent_from_specification(
        specifications[profile_key], profile_key=profile_key, seat=seat
    )


def improved_agent_from_specification(
    specification: AgentSpecification, *, profile_key: str, seat: int
):
    """A fresh improved policy for *seat* from an owned specification.

    Resolving the specification once and passing it in is what keeps a
    four-seat table from rebuilding the identity-bearing catalogue per seat.
    """

    from .factory import profile_of

    if type(seat) is not int or seat not in range(4):
        raise AgentsValidationError("seat must be an integer in 0..3")
    declared = improved_policies()
    if profile_key not in declared:
        raise AgentsValidationError(f"unknown improved profile {profile_key!r}")
    base = _base_specification(declared[profile_key].base_profile_key)
    return _policy_class(profile_key)(
        agent_id=specification.agent_id, profile=profile_of(base)
    )


def improved_agents_for_seats(
    profile_key: str, seats: Sequence[int] | None = None
) -> dict[int, object]:
    """Fresh, distinct improved policies for *seats*, resolved once."""

    specifications = improved_specifications_by_profile_key()
    if profile_key not in specifications:
        raise AgentsValidationError(f"unknown improved profile {profile_key!r}")
    specification = specifications[profile_key]
    chosen = tuple(range(4)) if seats is None else tuple(seats)
    if not frozenset(chosen) <= frozenset(range(4)):
        raise AgentsValidationError("seats must be a subset of 0..3")
    return {
        seat: improved_agent_from_specification(
            specification, profile_key=profile_key, seat=seat
        )
        for seat in chosen
    }


#: The policy the Phase 7 corpus generates with.  Recorded here rather than in
#: the corpus package so that a change of reference is one edit with one
#: identity consequence, and so the corpus manifest can cite it by name.
CORPUS_REFERENCE_PROFILE_KEY = "partner_aware_lead_v2"


def corpus_reference_specification() -> AgentSpecification:
    """The immutable specification of the Phase 7 corpus reference policy."""

    return improved_specifications_by_profile_key()[CORPUS_REFERENCE_PROFILE_KEY]


